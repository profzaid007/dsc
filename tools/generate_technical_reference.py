"""Generate source-derived documentation without reading secrets or runtime data."""
from pathlib import Path
import hashlib
import json
import re
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'docs/Technical Docs/technical-reference.md'

def rel(p):
    return p.relative_to(ROOT).as_posix()

def link(p, line=None):
    return f'[{rel(p)}{":" + str(line) if line else ""}](../../{quote(rel(p), safe="/")})'

def cell(value):
    return str(value).replace('|', '&#124;').replace('\n', '<br>').replace('\r', '')

def table(headers, rows):
    return ['| ' + ' | '.join(headers) + ' |', '| ' + ' | '.join(['---'] * len(headers)) + ' |'] + ['| ' + ' | '.join(cell(v) for v in row) + ' |' for row in rows] + ['']

sources = []
for directory in ['app', 'lib', 'hooks', 'types', 'pb_hooks', 'pb_migrations', 'backend/pb', 'local-backend', 'tests']:
    sources.extend(p for p in (ROOT / directory).rglob('*') if p.is_file() and p.suffix in {'.ts', '.tsx', '.js', '.mjs', '.cjs', '.json', '.ps1', '.py'} and not any(x in p.parts for x in ['node_modules', 'pb_data', '__pycache__']))
sources += [ROOT / 'package.json', ROOT / 'next.config.mjs']
sources = sorted(set(sources))
digest = hashlib.sha256()
for p in sources:
    digest.update(rel(p).encode())
    digest.update(p.read_bytes())
lines = ['# DSC source-derived technical reference', '', 'Generated by `python tools/generate_technical_reference.py`. This inventory describes repository sources, not a deployed database. No environment files, credentials, runtime data or remote services are read.', '', f'Source-content SHA-256: `{digest.hexdigest()}`', '', '## Page route inventory', '', 'Route groups in parentheses do not appear in URLs. Dynamic brackets represent route parameters. Presence of a page is not proof of public access; layouts and backend rules apply.', '']
rows = []
for p in sorted((ROOT / 'app').rglob('page.tsx')):
    parts = [v for v in p.parent.relative_to(ROOT / 'app').parts if not v.startswith('(')]
    rows.append(('/' + '/'.join(parts), link(p)))
lines += table(['Route', 'Implementation'], rows)
lines += ['## Custom HTTP endpoints', '', 'Statically declared route registrations from both backend trees are listed separately so differences remain visible. Authorization and full payload validation are implemented inside each handler and helper. Source links identify the authoritative implementation; these are not inferred OpenAPI schemas.', '']
rows = []
pattern = re.compile(r'routerAdd\(\s*([\'\"])([A-Z]+)\1\s*,\s*([\'\"])(.*?)\3', re.S)
for base in ['pb_hooks', 'backend/pb/pb_hooks']:
    for p in sorted((ROOT / base).glob('*.js')):
        text = p.read_text(encoding='utf-8-sig')
        for m in pattern.finditer(text):
            rows.append((m[2], m[4], link(p, text[:m.start()].count('\n') + 1)))
for p in sorted((ROOT / 'app/api').rglob('route.ts')):
    text = p.read_text(encoding='utf-8-sig')
    for m in re.finditer(r'export\s+async\s+function\s+(GET|POST|PUT|PATCH|DELETE)\b', text):
        rows.append((m[1], '/' + p.parent.relative_to(ROOT / 'app').as_posix(), link(p, text[:m.start()].count('\n') + 1)))
lines += table(['Method', 'Path', 'Registration'], rows)
lines += ['## Snapshot data dictionary', '', 'Source: `backend/pb/pb_schema.json`. Later migrations can add or replace these definitions. Empty rules allow public access in PocketBase semantics; null rules restrict ordinary API access. Custom hooks can impose further checks. Auth collections also carry PocketBase authentication behavior.', '']
schema = json.loads((ROOT / 'backend/pb/pb_schema.json').read_text(encoding='utf-8-sig'))
if isinstance(schema, dict):
    schema = schema.get('collections', [])
names = {c['id']: c['name'] for c in schema}
lines += [f'Snapshot contains **{len(schema)} collections**, including **{sum(c.get("type") == "view" for c in schema)} views**.', '']
for c in schema:
    lines += [f'### `{c["name"]}`', '', f'Type: `{c.get("type", "base")}`; collection ID: `{c["id"]}`.', '']
    rows = []
    for f in c.get('fields', c.get('schema', [])):
        opts = {k: v for k, v in f.items() if k not in {'id', 'name', 'type', 'required', 'hidden', 'presentable', 'system'} and v is not None}
        if 'collectionId' in opts:
            opts['collectionName'] = names.get(opts['collectionId'], 'external/unknown')
        rows.append((f['name'], f['type'], f.get('required', False), f.get('hidden', False), json.dumps(opts, ensure_ascii=False, separators=(',', ':'))))
    lines += table(['Field', 'Type', 'Required', 'Hidden', 'Constraints/options'], rows)
    lines += ['Access rules:', '', '```json', json.dumps({k: c.get(k) for k in ['listRule', 'viewRule', 'createRule', 'updateRule', 'deleteRule']}, ensure_ascii=False, indent=2), '```', '']
    if c.get('indexes'):
        lines += ['Indexes:', '', '```sql', '\n'.join(c['indexes']), '```', '']
    if c.get('viewQuery'):
        lines += ['View definition:', '', '```sql', c['viewQuery'], '```', '']
lines += ['## Migration inventory', '', 'File existence does not establish whether a migration ran. Inspect the target database migration history before deployment. Legacy and local bootstrap migrations have different purposes.', '']
for base in ['pb_migrations', 'backend/pb/pb_migrations', 'backend/pb/pb_migrations_legacy', 'local-backend']:
    lines += [f'### `{base}`', '']
    lines += [f'- {link(p)}' for p in sorted((ROOT / base).glob('*.js'))] + ['']
lines += ['## Backend deployment-copy comparison', '', 'Byte-for-byte comparison; differences may be intentional but must be reviewed before choosing a deployment source.', '']
rows = []
for local, deployed in [('pb_hooks', 'backend/pb/pb_hooks'), ('pb_migrations', 'backend/pb/pb_migrations')]:
    a, b = ROOT / local, ROOT / deployed
    paths = sorted({p.relative_to(a) for p in a.rglob('*.js')} | {p.relative_to(b) for p in b.rglob('*.js')})
    for name in paths:
        x, y = a / name, b / name
        status = 'identical' if x.exists() and y.exists() and x.read_bytes() == y.read_bytes() else 'different' if x.exists() and y.exists() else 'local only' if x.exists() else 'deployment only'
        rows.append((f'{local}/{name.as_posix()}', status))
lines += table(['Local relative file', 'Compared with deployment tree'], rows)
lines += ['## Environment-variable source references', '', 'Names and source locations only. No configured values are included. Includes test/tool variables; a reference does not mean a variable is mandatory in production.', '']
refs = {}
patterns = [re.compile(r'process\.env\.([A-Z][A-Z0-9_]*)'), re.compile(r'\$os\.getenv\([\'\"]([A-Z][A-Z0-9_]*)')]
for p in sources:
    text = p.read_text(encoding='utf-8-sig', errors='replace')
    for pat in patterns:
        for m in pat.finditer(text):
            refs.setdefault(m[1], set()).add(link(p, text[:m.start()].count('\n') + 1))
lines += table(['Variable', 'References'], [(k, '<br>'.join(sorted(v))) for k, v in sorted(refs.items())])
lines += ['## Package scripts', '']
package = json.loads((ROOT / 'package.json').read_text(encoding='utf-8-sig'))
lines += table(['Script', 'Command'], [(k, f'`{v}`') for k, v in package['scripts'].items()])
lines += ['## Test inventory', '', 'Inventory only: tests were not executed by this generator. Review integration targets and isolation before running.', '']
lines += [f'- {link(p)}' for p in sorted((ROOT / 'tests').glob('*')) if p.is_file()] + ['']
lines += ['## Feature documentation index', '']
lines += [f'- [{p.stem}](../{p.name})' for p in sorted((ROOT / 'docs').glob('*.md')) if p.name not in {'technical-reference.md', 'technical-documentation.md'}] + ['']
OUT.write_text('\n'.join(lines), encoding='utf-8')
print(f'Generated {rel(OUT)}: {len(rows)} backend copy comparisons, {len(schema)} snapshot collections, {len(lines)} lines.')

