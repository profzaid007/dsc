// Keep the deployed hook trees, standalone additive migration, and canonical
// collection snapshot aligned. No running database is contacted by this tool.
const fs = require("node:fs")
const path = require("node:path")
const vm = require("node:vm")
const root = path.resolve(__dirname, "..")
const read = (p) => fs.readFileSync(path.join(root, p), "utf8")
const load = (source) => {
  const context = { module: { exports: {} }, Set }
  vm.runInNewContext(source, context)
  return context.module.exports
}
const policySource = read("backend/pb/pb_hooks/lib/security-policy.js")
const installerSource = read("backend/pb/security-migration-source.js")
const policy = load(policySource)
const migration =
  "// Generated by node tools/build-security-artifacts.cjs; edit the source files.\n" +
  "migrate((app) => {\nconst policy = (() => { const module = {exports:{}};\n" +
  policySource +
  "\nreturn module.exports })();\n" +
  installerSource.replace(
    "module.exports = installSecurity",
    "installSecurity(app, policy)"
  ) +
  '\n}, () => { throw new Error("Security rollback requires a reviewed backup and coordinated frontend rollback; grants and audit logs must be preserved.") });\n'
fs.writeFileSync(
  path.join(root, "pb_migrations/1792900000_security_management.js"),
  migration
)
fs.mkdirSync(path.join(root, "backend/pb/pb_migrations"), { recursive: true })
fs.writeFileSync(
  path.join(root, "backend/pb/pb_migrations/1792900000_security_management.js"),
  migration
)
for (const name of [
  "lib/security-policy.js",
  "lib/security-management.js",
  "lib/security-payments.js",
  "security-management.pb.js",
]) {
  const source = path.join(root, "backend/pb/pb_hooks", name)
  if (fs.existsSync(source))
    fs.copyFileSync(source, path.join(root, "pb_hooks", name))
}
// Replaying schema changes into a schema-only adapter avoids two definitions of
// fields/rules. Data seeding remains in the additive migration.
const schemaPath = path.join(root, "backend/pb/pb_schema.json")
const schema = require("./security-base-schema.cjs")(root)
class Fields extends Array {
  add(f) {
    this.push(f)
  }
  getByName(n) {
    return this.find((f) => f.name === n)
  }
}
const collections = schema.map((c) => ({ ...c, fields: Fields.from(c.fields) }))
const app = {
  findCollectionByNameOrId(n) {
    const c = collections.find((c) => c.name === n || c.id === n)
    if (!c) throw Error(n)
    return c
  },
  findRecordsByFilter() {
    return []
  },
  save(c) {
    if (c.name && !collections.includes(c)) collections.push(c)
  },
}
class Collection {
  constructor(c) {
    Object.assign(this, c)
    this.fields = Fields.from(c.fields)
  }
}
class Record {
  constructor(c) {
    this.id = "buildonly000001"
    this._collection = c
  }
  set() {}
}
class SelectField {
  constructor(f) {
    Object.assign(this, { type: "select" }, f)
  }
}
const context = { module: { exports: {} }, Collection, Record, SelectField }
vm.runInNewContext(installerSource, context)
context.module.exports(app, policy)
fs.writeFileSync(schemaPath, JSON.stringify(collections, null, 2) + "\n")
console.log(
  "Generated security migration, canonical schema, and runtime hook copies."
)

// Additive upgrade for installations that already applied security management.
const generalRoles =
  "// Generated by tools/build-security-artifacts.cjs.\nmigrate(app => {\nconst policy = (() => {const module={exports:{}};\n" +
  policySource +
  "\nreturn module.exports})();\n" +
  read("backend/pb/general-role-migration-source.js").replace(
    "module.exports = upgradeRoleAssignment",
    "upgradeRoleAssignment(app, policy)"
  ) +
  "\n}, () => {throw new Error('Restore a reviewed backup to roll back role delegation.')});\n"
for (const folder of ["pb_migrations", "backend/pb/pb_migrations"])
  fs.writeFileSync(
    path.join(root, folder, "1795100000_general_role_assignment.js"),
    generalRoles
  )
