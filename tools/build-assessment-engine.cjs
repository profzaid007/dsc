// Generate PocketBase's script from the same engine used by frontend types/tests.
const fs = require("node:fs")
const ts = require("typescript")
const source = fs.readFileSync("lib/assessments/engine.ts", "utf8")
const output = "// Generated by tools/build-assessment-engine.cjs; edit lib/assessments/engine.ts.\n" + ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019 },
}).outputText
